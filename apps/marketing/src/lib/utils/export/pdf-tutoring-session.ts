import { sanitize as baseSanitize } from '@core/utils/export/pdf-course-export';

interface SessionMessage {
  role: 'user' | 'assistant' | 'system-notice';
  content: string;
  timestamp: Date;
  isError?: boolean;
  extractedProblem?: string;
}

function sanitizeForPDF(text: string): string {
  let s = baseSanitize(text);
  s = s.replace(/\u2026/g, '...');
  s = s.replace(/[\u00A0\u2000-\u200B\u202F\u205F\u3000]/g, ' ');
  s = s.replace(/\uFEFF/g, '');
  // Strip markdown bold/italic markers for cleaner PDF
  s = s.replace(/\*\*(.*?)\*\*/g, '$1');
  s = s.replace(/\*(.*?)\*/g, '$1');
  s = s.replace(/`(.*?)`/g, '$1');
  s = s.replace(/[^\x00-\xFF]/g, '?');
  return s;
}

export async function exportTutoringSessionPDF(
  messages: SessionMessage[],
  subjectName: string
): Promise<void> {
  const { default: jsPDF } = await import('jspdf');
  const pdf = new jsPDF('p', 'mm', 'a4');
  const pageWidth = pdf.internal.pageSize.getWidth();
  const margin = 18;
  const contentWidth = pageWidth - margin * 2;
  const textAreaWidth = contentWidth - 8;
  let y = 0;
  const LINE_HEIGHT = 4.5;

  const addPageIfNeeded = (space: number) => {
    if (y + space > 272) { pdf.addPage(); y = 20; }
  };

  const drawWrappedText = (
    text: string, x: number, maxWidth: number,
    opts: { size?: number; style?: string; color?: [number, number, number]; lineHeight?: number } = {}
  ) => {
    const { size = 9, style = 'normal', color = [74, 85, 104], lineHeight = LINE_HEIGHT } = opts;
    pdf.setFont('helvetica', style);
    pdf.setFontSize(size);
    pdf.setTextColor(...color);
    const safe = sanitizeForPDF(text);
    const lines: string[] = pdf.splitTextToSize(safe, maxWidth);
    for (const line of lines) {
      addPageIfNeeded(lineHeight + 1);
      pdf.text(line, x, y);
      y += lineHeight;
    }
  };

  // ── Header Banner ──
  pdf.setFillColor(147, 51, 234);
  pdf.rect(0, 0, pageWidth, 38, 'F');
  pdf.setFillColor(126, 34, 206);
  pdf.rect(0, 35, pageWidth, 3, 'F');

  pdf.setTextColor(255, 255, 255);
  pdf.setFontSize(20);
  pdf.setFont('helvetica', 'bold');
  pdf.text('Tutoring Session Transcript', margin, 16);
  pdf.setFontSize(10);
  pdf.setFont('helvetica', 'normal');
  pdf.text('Generated by Evelyn Learning', margin, 24);
  const dateStr = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
  pdf.text(sanitizeForPDF(dateStr), margin, 30);
  y = 48;

  // ── Session info ──
  drawWrappedText(`Subject: ${subjectName}`, margin, contentWidth, {
    size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 6,
  });
  const msgCount = messages.filter(m => m.role === 'user').length;
  drawWrappedText(`Student questions: ${msgCount}`, margin, contentWidth, {
    size: 10, style: 'normal', color: [100, 116, 139], lineHeight: 6,
  });
  y += 4;

  // ── Academic integrity notice ──
  addPageIfNeeded(16);
  pdf.setFillColor(240, 253, 244);
  pdf.roundedRect(margin, y, contentWidth, 12, 2, 2, 'F');
  drawWrappedText(
    'This session used the Socratic tutoring method. The AI guided the student toward understanding through questions and hints rather than providing direct answers.',
    margin + 4, textAreaWidth,
    { size: 8, style: 'italic', color: [22, 101, 52], lineHeight: 4 }
  );
  y += 6;

  // ── Messages ──
  addPageIfNeeded(10);
  drawWrappedText('Session Transcript', margin, contentWidth, {
    size: 12, style: 'bold', color: [26, 32, 44], lineHeight: 8,
  });

  // Filter out the initial greeting and errors for a cleaner transcript
  const transcriptMessages = messages.filter(m => !m.isError);

  for (const msg of transcriptMessages) {
    addPageIfNeeded(14);

    if (msg.role === 'system-notice') {
      // Extracted problem notice
      pdf.setFillColor(239, 246, 255);
      const noticeText = sanitizeForPDF(msg.content);
      const noticeLines: string[] = pdf.splitTextToSize(noticeText, textAreaWidth);
      const noticeHeight = noticeLines.length * LINE_HEIGHT + 6;
      pdf.roundedRect(margin, y - 2, contentWidth, noticeHeight, 2, 2, 'F');
      drawWrappedText(msg.content, margin + 4, textAreaWidth, {
        size: 8.5, style: 'italic', color: [30, 64, 175],
      });
      y += 4;
      continue;
    }

    const isUser = msg.role === 'user';
    const label = isUser ? 'STUDENT' : 'TUTOR';
    const labelColor: [number, number, number] = isUser ? [147, 51, 234] : [22, 163, 74];
    const textColor: [number, number, number] = isUser ? [55, 65, 81] : [55, 65, 81];

    // Role badge
    pdf.setFont('helvetica', 'bold');
    pdf.setFontSize(7);
    const badgeW = pdf.getTextWidth(label) + 6;
    pdf.setFillColor(...labelColor);
    pdf.roundedRect(margin, y - 3, badgeW, 4.5, 1, 1, 'F');
    pdf.setTextColor(255, 255, 255);
    pdf.text(label, margin + 3, y);
    y += 5;

    // Time
    const timeStr = msg.timestamp instanceof Date
      ? msg.timestamp.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
      : '';
    if (timeStr) {
      pdf.setFont('helvetica', 'normal');
      pdf.setFontSize(7);
      pdf.setTextColor(156, 163, 175);
      pdf.text(timeStr, margin + badgeW + 4, y - 5);
    }

    // Message content
    drawWrappedText(msg.content, margin + 4, textAreaWidth, {
      size: 9, style: 'normal', color: textColor,
    });
    y += 4;
  }

  // ── Footer ──
  const totalPages = pdf.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    pdf.setPage(i);
    pdf.setDrawColor(226, 232, 240);
    pdf.line(margin, 282, pageWidth - margin, 282);
    pdf.setFont('helvetica', 'normal');
    pdf.setFontSize(7);
    pdf.setTextColor(156, 163, 175);
    pdf.text('Generated by Evelyn Learning -- AI Homework Helper (Socratic Tutoring)', margin, 287);
    pdf.text(`Page ${i} of ${totalPages}`, pageWidth - margin - 22, 287);
  }

  const filename = `Tutoring_Session_${subjectName.replace(/[^a-zA-Z0-9]+/g, '_')}_${new Date().toISOString().split('T')[0]}.pdf`;
  pdf.save(filename);
}
