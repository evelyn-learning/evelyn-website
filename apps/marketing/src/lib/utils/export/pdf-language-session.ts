import { sanitize as baseSanitize } from '@core/utils/export/pdf-course-export';

interface SessionMessage {
  role: 'user' | 'assistant' | 'system';
  content: string;
  translation?: string;
  correction?: string;
}

interface VocabWord {
  word: string;
  translation: string;
  context?: string;
}

function sanitizeForPDF(text: string): string {
  let s = baseSanitize(text);
  s = s.replace(/\u2026/g, '...');
  s = s.replace(/[\u00A0\u2000-\u200B\u202F\u205F\u3000]/g, ' ');
  s = s.replace(/\uFEFF/g, '');
  s = s.replace(/[^\x00-\xFF]/g, '?');
  return s;
}

export async function exportLanguageSessionPDF(
  messages: SessionMessage[],
  vocabulary: VocabWord[],
  languageName: string,
  scenarioName: string,
  difficulty: string,
  corrections: number
): Promise<void> {
  const { default: jsPDF } = await import('jspdf');
  const pdf = new jsPDF('p', 'mm', 'a4');
  const pageWidth = pdf.internal.pageSize.getWidth();
  const margin = 18;
  const contentWidth = pageWidth - margin * 2;
  const textAreaWidth = contentWidth - 8;
  let y = 0;
  const LINE_HEIGHT = 4.5;

  const addPageIfNeeded = (space: number) => {
    if (y + space > 272) { pdf.addPage(); y = 20; }
  };

  const drawWrappedText = (
    text: string, x: number, maxWidth: number,
    opts: { size?: number; style?: string; color?: [number, number, number]; lineHeight?: number } = {}
  ) => {
    const { size = 9, style = 'normal', color = [74, 85, 104], lineHeight = LINE_HEIGHT } = opts;
    pdf.setFont('helvetica', style);
    pdf.setFontSize(size);
    pdf.setTextColor(...color);
    const safe = sanitizeForPDF(text);
    const lines: string[] = pdf.splitTextToSize(safe, maxWidth);
    for (const line of lines) {
      addPageIfNeeded(lineHeight + 1);
      pdf.text(line, x, y);
      y += lineHeight;
    }
  };

  // Header
  pdf.setFillColor(79, 70, 229); // indigo-600
  pdf.rect(0, 0, pageWidth, 38, 'F');
  pdf.setFillColor(67, 56, 202);
  pdf.rect(0, 35, pageWidth, 3, 'F');

  pdf.setTextColor(255, 255, 255);
  pdf.setFontSize(20);
  pdf.setFont('helvetica', 'bold');
  pdf.text('Language Practice Session', margin, 16);
  pdf.setFontSize(10);
  pdf.setFont('helvetica', 'normal');
  pdf.text('Generated by Evelyn Learning', margin, 24);
  const dateStr = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
  pdf.text(sanitizeForPDF(dateStr), margin, 30);
  y = 48;

  // Session info
  drawWrappedText(`Language: ${languageName}`, margin, contentWidth, { size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 6 });
  drawWrappedText(`Scenario: ${scenarioName} | Level: ${difficulty}`, margin, contentWidth, { size: 10, color: [100, 116, 139], lineHeight: 6 });
  const exchanges = messages.filter(m => m.role === 'user').length;
  drawWrappedText(`Exchanges: ${exchanges} | Corrections: ${corrections} | New Vocabulary: ${vocabulary.length}`, margin, contentWidth, { size: 10, color: [100, 116, 139], lineHeight: 6 });
  y += 4;

  // Vocabulary section
  if (vocabulary.length > 0) {
    addPageIfNeeded(14);
    drawWrappedText('Vocabulary Learned', margin, contentWidth, { size: 12, style: 'bold', color: [26, 32, 44], lineHeight: 8 });

    for (const word of vocabulary) {
      addPageIfNeeded(10);
      drawWrappedText(`${word.word} -- ${word.translation}`, margin + 4, textAreaWidth, {
        size: 9, style: 'bold', color: [79, 70, 229],
      });
      if (word.context) {
        drawWrappedText(`"${word.context}"`, margin + 8, textAreaWidth - 4, {
          size: 8, style: 'italic', color: [100, 116, 139],
        });
      }
      y += 2;
    }
    y += 4;
  }

  // Conversation transcript
  addPageIfNeeded(10);
  drawWrappedText('Conversation Transcript', margin, contentWidth, { size: 12, style: 'bold', color: [26, 32, 44], lineHeight: 8 });

  for (const msg of messages) {
    if (msg.role === 'system') continue;
    addPageIfNeeded(14);

    const isUser = msg.role === 'user';
    const label = isUser ? 'STUDENT' : 'PARTNER';
    const labelColor: [number, number, number] = isUser ? [79, 70, 229] : [22, 163, 74];

    pdf.setFont('helvetica', 'bold');
    pdf.setFontSize(7);
    const badgeW = pdf.getTextWidth(label) + 6;
    pdf.setFillColor(...labelColor);
    pdf.roundedRect(margin, y - 3, badgeW, 4.5, 1, 1, 'F');
    pdf.setTextColor(255, 255, 255);
    pdf.text(label, margin + 3, y);
    y += 5;

    drawWrappedText(msg.content, margin + 4, textAreaWidth, { size: 9, color: [55, 65, 81] });
    if (msg.translation && !isUser) {
      drawWrappedText(`(${msg.translation})`, margin + 4, textAreaWidth, { size: 8, style: 'italic', color: [100, 116, 139] });
    }
    if (msg.correction) {
      drawWrappedText(`Correction: ${msg.correction}`, margin + 4, textAreaWidth, { size: 8, style: 'italic', color: [202, 138, 4] });
    }
    y += 3;
  }

  // Footer
  const totalPages = pdf.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    pdf.setPage(i);
    pdf.setDrawColor(226, 232, 240);
    pdf.line(margin, 282, pageWidth - margin, 282);
    pdf.setFont('helvetica', 'normal');
    pdf.setFontSize(7);
    pdf.setTextColor(156, 163, 175);
    pdf.text('Generated by Evelyn Learning -- Language Learning AI', margin, 287);
    pdf.text(`Page ${i} of ${totalPages}`, pageWidth - margin - 22, 287);
  }

  const filename = `Language_Session_${languageName}_${new Date().toISOString().split('T')[0]}.pdf`;
  pdf.save(filename);
}
