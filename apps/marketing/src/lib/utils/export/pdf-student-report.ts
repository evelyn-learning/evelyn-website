import { sanitize as baseSanitize } from '@core/utils/export/pdf-course-export';

interface SubjectData {
  name: string;
  progress: number;
  trend: 'up' | 'down' | 'stable';
  recentScore: number;
}

interface ActivityData {
  date: string;
  action: string;
  subject: string;
  result?: string;
}

export interface StudentReportData {
  name: string;
  grade: string;
  overallProgress: number;
  streak: number;
  subjects: SubjectData[];
  recentActivity: ActivityData[];
  strengths: string[];
  areasForImprovement: string[];
}

export interface ClassContextData {
  totalStudents: number;
  averageProgress: number;
  subjectAverages: { name: string; classAverage: number }[];
}

function sanitizeForPDF(text: string): string {
  let s = baseSanitize(text);
  s = s.replace(/\u2026/g, '...');
  s = s.replace(/[\u00A0\u2000-\u200B\u202F\u205F\u3000]/g, ' ');
  s = s.replace(/\uFEFF/g, '');
  s = s.replace(/[^\x00-\xFF]/g, '?');
  return s;
}

export async function exportStudentReportPDF(
  student: StudentReportData,
  classContext?: ClassContextData
): Promise<void> {
  const { default: jsPDF } = await import('jspdf');
  const pdf = new jsPDF('p', 'mm', 'a4');
  const pageWidth = pdf.internal.pageSize.getWidth();
  const margin = 18;
  const contentWidth = pageWidth - margin * 2;
  const textAreaWidth = contentWidth - 8;
  let y = 0;
  const LINE_HEIGHT = 4.5;

  const addPageIfNeeded = (space: number) => {
    if (y + space > 272) { pdf.addPage(); y = 20; }
  };

  const drawWrappedText = (
    text: string, x: number, maxWidth: number,
    opts: { size?: number; style?: string; color?: [number, number, number]; lineHeight?: number } = {}
  ) => {
    const { size = 9, style = 'normal', color = [74, 85, 104], lineHeight = LINE_HEIGHT } = opts;
    pdf.setFont('helvetica', style);
    pdf.setFontSize(size);
    pdf.setTextColor(...color);
    const safe = sanitizeForPDF(text);
    const lines: string[] = pdf.splitTextToSize(safe, maxWidth);
    for (const line of lines) {
      addPageIfNeeded(lineHeight + 1);
      pdf.text(line, x, y);
      y += lineHeight;
    }
  };

  const getProgressColor = (progress: number): [number, number, number] => {
    if (progress >= 80) return [22, 163, 74];
    if (progress >= 60) return [234, 179, 8];
    return [239, 68, 68];
  };

  // ── Header Banner ──
  pdf.setFillColor(37, 99, 235); // blue-600
  pdf.rect(0, 0, pageWidth, 38, 'F');
  pdf.setFillColor(29, 78, 216); // blue-700
  pdf.rect(0, 35, pageWidth, 3, 'F');

  pdf.setTextColor(255, 255, 255);
  pdf.setFontSize(20);
  pdf.setFont('helvetica', 'bold');
  pdf.text('Student Progress Report', margin, 16);
  pdf.setFontSize(10);
  pdf.setFont('helvetica', 'normal');
  pdf.text('Generated by Evelyn Learning', margin, 24);
  const dateStr = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
  pdf.text(sanitizeForPDF(dateStr), margin, 30);
  y = 48;

  // ── Student Info ──
  addPageIfNeeded(30);
  pdf.setFillColor(248, 250, 252);
  pdf.roundedRect(margin, y, contentWidth, 28, 3, 3, 'F');

  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(16);
  pdf.setTextColor(26, 32, 44);
  pdf.text(sanitizeForPDF(student.name), margin + 6, y + 10);

  pdf.setFont('helvetica', 'normal');
  pdf.setFontSize(10);
  pdf.setTextColor(100, 116, 139);
  pdf.text(`Grade: ${student.grade}`, margin + 6, y + 18);
  pdf.text(`Streak: ${student.streak} days`, margin + 50, y + 18);

  // Overall progress
  const progressColor = getProgressColor(student.overallProgress);
  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(22);
  pdf.setTextColor(...progressColor);
  pdf.text(`${student.overallProgress}%`, margin + contentWidth - 30, y + 16);
  pdf.setFont('helvetica', 'normal');
  pdf.setFontSize(8);
  pdf.setTextColor(100, 116, 139);
  pdf.text('Overall', margin + contentWidth - 30, y + 22);
  y += 36;

  // ── Subject Progress ──
  addPageIfNeeded(14);
  drawWrappedText('Subject Progress', margin, contentWidth, {
    size: 12, style: 'bold', color: [26, 32, 44], lineHeight: 8,
  });

  for (const subject of student.subjects) {
    addPageIfNeeded(18);
    const subColor = getProgressColor(subject.progress);
    const trendLabel = subject.trend === 'up' ? '(Improving)' : subject.trend === 'down' ? '(Declining)' : '(Stable)';
    const trendColor: [number, number, number] = subject.trend === 'up' ? [22, 163, 74] : subject.trend === 'down' ? [220, 38, 38] : [100, 116, 139];

    // Subject name and score
    pdf.setFont('helvetica', 'bold');
    pdf.setFontSize(10);
    pdf.setTextColor(26, 32, 44);
    pdf.text(sanitizeForPDF(subject.name), margin + 4, y);

    pdf.setFont('helvetica', 'normal');
    pdf.setFontSize(9);
    pdf.setTextColor(...trendColor);
    pdf.text(sanitizeForPDF(trendLabel), margin + 35, y);

    pdf.setFont('helvetica', 'bold');
    pdf.setTextColor(...subColor);
    pdf.text(`${subject.progress}%`, margin + contentWidth - 20, y);
    y += 4;

    // Progress bar
    pdf.setFillColor(229, 231, 235);
    pdf.roundedRect(margin + 4, y, textAreaWidth, 3, 1.5, 1.5, 'F');
    pdf.setFillColor(...subColor);
    pdf.roundedRect(margin + 4, y, textAreaWidth * (subject.progress / 100), 3, 1.5, 1.5, 'F');
    y += 5;

    pdf.setFont('helvetica', 'normal');
    pdf.setFontSize(8);
    pdf.setTextColor(100, 116, 139);
    pdf.text(`Last score: ${subject.recentScore}%`, margin + 4, y);

    // Class comparison if available
    if (classContext) {
      const classAvg = classContext.subjectAverages.find(s => s.name === subject.name);
      if (classAvg) {
        const diff = subject.progress - classAvg.classAverage;
        const diffStr = diff >= 0 ? `+${diff}` : `${diff}`;
        const diffColor: [number, number, number] = diff >= 0 ? [22, 163, 74] : [220, 38, 38];
        pdf.setTextColor(...diffColor);
        pdf.text(`${diffStr} vs class avg (${classAvg.classAverage}%)`, margin + 50, y);
      }
    }
    y += 6;
  }
  y += 2;

  // ── Recent Activity ──
  if (student.recentActivity.length > 0) {
    addPageIfNeeded(14);
    drawWrappedText('Recent Activity', margin, contentWidth, {
      size: 12, style: 'bold', color: [26, 32, 44], lineHeight: 8,
    });

    for (const activity of student.recentActivity) {
      addPageIfNeeded(10);
      const line = `${activity.action} ${activity.subject}${activity.result ? ` -- ${activity.result}` : ''}`;
      drawWrappedText(line, margin + 4, textAreaWidth - 30, {
        size: 9, style: 'normal', color: [55, 65, 81],
      });
      // Date right-aligned
      pdf.setFont('helvetica', 'normal');
      pdf.setFontSize(8);
      pdf.setTextColor(156, 163, 175);
      pdf.text(sanitizeForPDF(activity.date), margin + contentWidth - 4, y - LINE_HEIGHT, { align: 'right' });
      y += 2;
    }
    y += 2;
  }

  // ── Strengths ──
  if (student.strengths.length > 0) {
    addPageIfNeeded(14);
    drawWrappedText('Strengths', margin, contentWidth, {
      size: 12, style: 'bold', color: [26, 32, 44], lineHeight: 8,
    });
    for (const strength of student.strengths) {
      drawWrappedText(`+ ${strength}`, margin + 4, textAreaWidth, {
        size: 9, style: 'normal', color: [22, 163, 74],
      });
      y += 1;
    }
    y += 2;
  }

  // ── Areas for Improvement ──
  if (student.areasForImprovement.length > 0) {
    addPageIfNeeded(14);
    drawWrappedText('Areas for Improvement', margin, contentWidth, {
      size: 12, style: 'bold', color: [26, 32, 44], lineHeight: 8,
    });
    for (const area of student.areasForImprovement) {
      drawWrappedText(`- ${area}`, margin + 4, textAreaWidth, {
        size: 9, style: 'normal', color: [202, 138, 4],
      });
      y += 1;
    }
  }

  // ── Footer ──
  const totalPages = pdf.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    pdf.setPage(i);
    pdf.setDrawColor(226, 232, 240);
    pdf.line(margin, 282, pageWidth - margin, 282);
    pdf.setFont('helvetica', 'normal');
    pdf.setFontSize(7);
    pdf.setTextColor(156, 163, 175);
    pdf.text('Generated by Evelyn Learning -- Student Analytics Dashboard', margin, 287);
    pdf.text(`Page ${i} of ${totalPages}`, pageWidth - margin - 22, 287);
  }

  const filename = `Student_Report_${student.name.replace(/[^a-zA-Z0-9]+/g, '_')}_${new Date().toISOString().split('T')[0]}.pdf`;
  pdf.save(filename);
}
