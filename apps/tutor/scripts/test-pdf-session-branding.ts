/**
 * PDF export branding — GreenApple pilot (task 13, spec §8.5): "PDF has no
 * Evelyn branding" for a partner whose `branding.product_name` is set.
 *
 * exportTutorSessionPDF (pdf-tutor-session.ts) is 'use client' and uses
 * browser globals (canvas, Image, window.Desmos) in its whiteboard-visual
 * branches, but its jsPDF core does NOT require a DOM — jsPDF ships a
 * dedicated Node build (dist/jspdf.node.js) whose `.save()` writes straight
 * to disk via `fs.writeFileSync`, no browser APIs involved (verified
 * empirically: a session with an empty whiteboardCommands array never
 * touches the canvas/Image paths, so the exporter runs end-to-end under
 * plain `npx tsx`). That lets this test exercise the REAL exporter and
 * inspect the actual PDF bytes, rather than falling back to a title/
 * filename-only helper.
 *
 * jsPDF's default content streams are uncompressed, so the header/footer
 * text we care about — "Generated by ${brandName}" / "Generated by
 * ${brandName} -- AI Voice Tutor" — survives as literal `(...) Tj` operators
 * in the raw file bytes (confirmed empirically against the pre-task-13
 * baseline, which contained two `Evelyn Learning` occurrences). Plain
 * substring checks on the written file are therefore a faithful assertion
 * of what a partner would see if they opened the PDF and searched it for
 * "Evelyn".
 *
 * Runs in a scratch cwd (os.tmpdir()) so the generated .pdf never lands in
 * the repo, and always cleans up — including on failure.
 */
import { mkdtempSync, readFileSync, rmSync, readdirSync } from 'fs';
import { tmpdir } from 'os';
import { join } from 'path';

let passed = 0;
let failed = 0;
function assert(cond: boolean, name: string) {
  if (cond) { passed++; console.log(`  ✓ ${name}`); }
  else { failed++; console.log(`  ✗ ${name}`); }
}

async function exportInto(
  scratchDir: string,
  productName: string | undefined,
): Promise<string> {
  const { exportTutorSessionPDF } = await import('../src/lib/utils/export/pdf-tutor-session');
  const prevCwd = process.cwd();
  process.chdir(scratchDir);
  try {
    await exportTutorSessionPDF(
      [
        { id: '1', timestamp: new Date(), role: 'tutor', text: 'Let us work through this problem together.' },
        { id: '2', timestamp: new Date(), role: 'student', text: 'Okay, I think x is 4.' },
      ],
      [],
      'Fractions Review',
      'homework-help',
      'Test Student',
      productName ? { subject: 'math', level: '6', productName } : { subject: 'math', level: '6' },
    );
  } finally {
    process.chdir(prevCwd);
  }
  const pdfFiles = readdirSync(scratchDir).filter((f) => f.endsWith('.pdf'));
  if (pdfFiles.length !== 1) {
    throw new Error(`expected exactly one .pdf in scratch dir, found ${pdfFiles.length}: ${pdfFiles.join(', ')}`);
  }
  return readFileSync(join(scratchDir, pdfFiles[0]), 'latin1');
}

async function main() {
  // Case 1: partner branding present — GreenApple, spec §8.5.
  const scratchA = mkdtempSync(join(tmpdir(), 'pdf-branding-test-'));
  try {
    const pdfText = await exportInto(scratchA, 'GreenApple Homework Help');
    assert(pdfText.includes('GreenApple Homework Help'), 'productName set: PDF bytes contain "GreenApple Homework Help"');
    assert(!pdfText.includes('Evelyn'), 'productName set: PDF bytes contain NO "Evelyn" string (spec 8.5)');
  } finally {
    rmSync(scratchA, { recursive: true, force: true });
  }

  // Case 2: no productName (admin pages, retail) — default text unchanged.
  const scratchB = mkdtempSync(join(tmpdir(), 'pdf-branding-test-'));
  try {
    const pdfText = await exportInto(scratchB, undefined);
    assert(pdfText.includes('Evelyn Learning'), 'productName absent: PDF bytes still contain the default "Evelyn Learning"');
  } finally {
    rmSync(scratchB, { recursive: true, force: true });
  }

  console.log(`\n${passed} passed, ${failed} failed`);
  process.exit(failed > 0 ? 1 : 0);
}

main().catch((err) => {
  console.error('Fatal error running PDF branding test:', err);
  process.exit(1);
});
