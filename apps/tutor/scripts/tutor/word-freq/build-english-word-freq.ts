/**
 * Builds src/lib/tutor/voice/english-word-freq.ts: the most frequent English
 * words in our own lesson-plan seeds (no outside download), most frequent
 * first. Used by run-together-english.ts to split STT output like
 * "Haveyouevergotokaraoke" back into words.
 *
 *   npx tsx scripts/tutor/word-freq/build-english-word-freq.ts
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.join(__dirname, '../../..');
const SEEDS = path.join(ROOT, 'src/lib/tutor/lesson-plan/seeds');
const OUT = path.join(ROOT, 'src/lib/tutor/voice/english-word-freq.ts');
const TOP = 15000;

// Everyday spoken words a learner says that a school corpus under-represents
// (contractions, pronouns, greetings), placed at the top of the ranking.
const SPOKEN = [
  'i', 'you', 'he', 'she', 'we', 'they', 'it', 'me', 'my', 'your', 'our', 'their', 'his', 'her',
  'yes', 'no', 'okay', 'ok', 'hello', 'hi', 'thanks', 'thank', 'please', 'sorry',
  "i'm", "i've", "i'd", "i'll", "you're", "you've", "it's", "that's", "don't", "doesn't", "didn't",
  "haven't", "hasn't", "isn't", "aren't", "wasn't", "weren't", "can't", "won't", "couldn't",
  'have', 'has', 'had', 'ever', 'never', 'been', 'gone', 'went', 'go', 'goes', 'going', 'to',
  'yesterday', 'today', 'tomorrow', 'last', 'week', 'weekend', 'year', 'month', 'night',
  'played', 'play', 'golf', 'tried', 'try', 'ate', 'eat', 'eaten', 'saw', 'seen', 'see',
  'karaoke', 'sushi', 'kayaking', 'friend', 'friends', 'family', 'boss', 'coworkers', 'colleagues',
  'alone', 'with', 'meeting', 'office', 'company', 'work', 'job', 'trip', 'business',
];

const counts = new Map<string, number>();
for (const f of fs.readdirSync(SEEDS)) {
  if (!f.endsWith('.ts')) continue;
  const text = fs.readFileSync(path.join(SEEDS, f), 'utf8');
  for (const m of text.toLowerCase().matchAll(/[a-z]+(?:'[a-z]+)?/g)) {
    const w = m[0];
    if (w.length > 20) continue;
    counts.set(w, (counts.get(w) ?? 0) + 1);
  }
}
// Single letters other than a/i are noise in this use.
for (const w of [...counts.keys()]) if (w.length === 1 && w !== 'a' && w !== 'i') counts.delete(w);
const ranked = [...counts.entries()].filter(([, n]) => n >= 3).sort((a, b) => b[1] - a[1]).map(([w]) => w);
const seen = new Set<string>();
const words: string[] = [];
for (const w of [...SPOKEN, ...ranked]) {
  if (seen.has(w)) continue;
  seen.add(w);
  words.push(w);
  if (words.length >= TOP) break;
}
fs.writeFileSync(
  OUT,
  `// GENERATED by scripts/tutor/word-freq/build-english-word-freq.ts — do not edit.\n` +
  `// ${words.length} English words, most frequent first (lesson-plan seeds + spoken basics).\n` +
  `export const ENGLISH_WORDS_BY_FREQUENCY: string = ${JSON.stringify(words.join(' '))};\n`,
);
console.log(`wrote ${words.length} words to ${path.relative(ROOT, OUT)} (${fs.statSync(OUT).size} bytes)`);
