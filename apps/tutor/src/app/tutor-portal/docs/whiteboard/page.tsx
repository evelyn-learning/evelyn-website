import { whiteboardTypes, whiteboardCategories } from '../../data/whiteboard-types';

export default function WhiteboardPage() {
  const visualCategories = whiteboardCategories.filter((c) => c.id !== 'navigation');
  const navCategory = whiteboardCategories.find((c) => c.id === 'navigation');
  const visualTypes = whiteboardTypes.filter((t) => t.category !== 'navigation');
  const navTypes = whiteboardTypes.filter((t) => t.category === 'navigation');

  return (
    <div>
      <h1 className="mb-2 text-3xl font-bold text-slate-900">Whiteboard Types</h1>
      <p className="mb-8 text-lg text-slate-600">
        {whiteboardTypes.length} interactive visual types the AI tutor can generate in real-time.
      </p>

      <h2 className="mb-4 mt-8 text-xl font-semibold text-slate-900">Overview</h2>
      <p className="mb-6 text-sm text-slate-600">
        The whiteboard is the tutor&apos;s signature feature. As the AI explains a concept verbally,
        it simultaneously generates visuals — equations, graphs, diagrams, molecular structures —
        synchronized with the audio. The whiteboard supports multi-page navigation so students can
        refer back to previous work.
      </p>

      <div className="mb-8 grid gap-4 sm:grid-cols-3 lg:grid-cols-5">
        {visualCategories.map((cat) => (
          <div key={cat.id} className="rounded-lg border border-slate-200 p-4 text-center">
            <div className="text-2xl font-bold text-blue-600">{cat.count}</div>
            <div className="text-sm text-slate-600">{cat.name}</div>
          </div>
        ))}
      </div>

      {/* Visual types by category */}
      <h2 className="mb-4 mt-10 text-xl font-semibold text-slate-900">Visual Types</h2>
      {visualCategories.map((cat) => {
        const types = visualTypes.filter((t) => t.category === cat.id);
        return (
          <div key={cat.id} className="mt-8">
            <h3 className="mb-4 text-lg font-semibold text-slate-900">{cat.name}</h3>
            <div className="space-y-3">
              {types.map((type) => (
                <div key={type.id} className="rounded-lg border border-slate-200 p-4">
                  <div className="mb-1 flex items-center gap-3">
                    <h4 className="font-semibold text-slate-900">{type.name}</h4>
                    <code className="rounded bg-slate-100 px-2 py-0.5 text-xs text-slate-500">
                      {type.command}
                    </code>
                  </div>
                  <p className="mb-1 text-sm text-slate-600">{type.description}</p>
                  <p className="text-xs text-slate-400">Example: {type.exampleUse}</p>
                </div>
              ))}
            </div>
          </div>
        );
      })}

      {/* Navigation commands */}
      {navCategory && (
        <div className="mt-10">
          <h2 className="mb-4 text-xl font-semibold text-slate-900">Page Navigation</h2>
          <p className="mb-4 text-sm text-slate-600">
            The whiteboard organizes content into pages. The tutor creates new pages for new concepts
            and can navigate back to previous pages for review.
          </p>
          <div className="space-y-3">
            {navTypes.map((type) => (
              <div key={type.id} className="rounded-lg border border-slate-200 p-4">
                <div className="mb-1 flex items-center gap-3">
                  <h4 className="font-semibold text-slate-900">{type.name}</h4>
                  <code className="rounded bg-slate-100 px-2 py-0.5 text-xs text-slate-500">
                    {type.command}
                  </code>
                </div>
                <p className="text-sm text-slate-600">{type.description}</p>
              </div>
            ))}
          </div>
        </div>
      )}

      <h2 className="mb-3 mt-10 text-xl font-semibold text-slate-900">How Whiteboard Commands Work</h2>
      <p className="mb-4 text-sm text-slate-600">
        Whiteboard commands are generated by the AI as part of its response. When the tutor says
        &quot;Let me show you this equation,&quot; it simultaneously emits a{' '}
        <code className="rounded bg-slate-100 px-1.5 py-0.5 text-xs">showEquation</code> command
        that the whiteboard renderer picks up and displays. Partners do not need to implement
        whiteboard rendering — it is handled entirely within the embed.
      </p>
      <p className="text-sm text-slate-600">
        If you need whiteboard data for analytics (e.g., which visual types are most used), the{' '}
        <code className="rounded bg-slate-100 px-1.5 py-0.5 text-xs">whiteboard.generated</code>{' '}
        webhook event fires each time a visual is created, and the full whiteboard history is
        available via{' '}
        <code className="rounded bg-slate-100 px-1.5 py-0.5 text-xs">GET /sessions/:id/whiteboard</code>.
      </p>
    </div>
  );
}
