/**
 * Grade 6 World Geography — Place & Perception: Mapping Your Own Community.
 *
 * CONCEPT-LED closing row of Unit 8 (National Geography Standard 2). It does
 * not install a new idea; it applies two already-scoped Grade 6 skills to one
 * task -- sketching and describing a labeled map of a familiar community --
 * and adds the one piece neither of those skills covered on its own:
 * checking a finished, labeled map against a printed description and
 * correcting a label that fails that check.
 *
 * SCOPE GUARD: this row draws on two prior Grade 6 rows and adds nothing new
 * beyond combining and checking them.
 *   From `m6geo.mental-maps-and-spatial-thinking` (1.2) it takes connecting
 *   landmarks by the routes between them, named in order with the turns
 *   between them. It never adds a formal landmark/path/edge/node/district
 *   typology, and it never explains HOW a person's mind builds or updates
 *   that picture -- 1.2's own guard already places that out of scope for
 *   this course at any grade, and this row does not reopen it.
 *   From `m6geo.what-makes-a-place-unique` (8.1) it takes labeling something
 *   as a physical characteristic (occurring naturally, without being built
 *   or added by people) or a human characteristic (built or added by
 *   people). It never uses 8.1's activity category -- an activity is not a
 *   landmark that can sit at a fixed point along a route -- and it never
 *   asks whether a WHOLE community description is complete the way 8.1's
 *   two-question routine does; this row labels one landmark at a time, not
 *   a whole description.
 *   The skill this row owns, and 1.2 does not, is named in this row's own
 *   scope line -- "correctly labeling its key landmarks and features" --
 *   which 1.2's scope line never mentions. 1.2's check move only ever reran
 *   the order and the turns of a route; it never checked or corrected a
 *   label, because 1.2 never attached one to a landmark. This row's check
 *   goes one step further: given a finished, labeled sketch, confirm the
 *   order, the turn to the next landmark, AND the physical-or-human label
 *   all match the printed description -- and when a label fails that check,
 *   correct it. That is the entire difference between the two rows, and it
 *   is the reason this row exists after 1.2 rather than duplicating it.
 *   This row never compares two different places against each other (Grade
 *   6 row 8.3, `comparing-two-places`) and never addresses two people
 *   perceiving the same place differently (Grade 6 row 8.2,
 *   `how-people-perceive-places-differently`) -- every community here is
 *   one independent, invented place, sketched and checked once. It never
 *   names the formal/functional/perceptual region typology or the
 *   adapt/modify/depend human-environment-interaction framework -- both
 *   belong to Grade 7's `m7geo-u1-regions-and-place.ts`. What IS
 *   deliberately allowed, because that Grade 7 file sits close across the
 *   line: naming a handful of concrete landmark types (a school, a library,
 *   a fire station, a footbridge, a post office, a clubhouse, a stream, a
 *   hill, a patch of woods, a meadow) as plain nouns, in the same register
 *   8.1 uses for its own buildings and activities -- because the skill here
 *   is checking a label against a plain physical-or-human split, never
 *   analyzing why a community has the landmarks it has or sorting it into a
 *   named type of region. Every community in this file is invented; no real
 *   place is named anywhere, which keeps this row clear of any locality
 *   claim.
 *
 * DEPTH CEILING NOTE FOR THE FAN-OUT: every keyIdea and every item below is
 * answerable by DEFINE or CLASSIFY -- naming what a community map is built
 * from, and sorting a landmark, a label, or a finished labeled map as
 * matching or not matching a printed description. Nothing here explains WHY
 * a community has the landmarks it has, and no step chains two "because"
 * links together. Test 2 (the closed-typology test) is the one that came
 * closest to a real risk: labeling a landmark physical or human could look
 * like introducing a new named system for map elements. It is not a Test 2
 * breach because it is not new -- it is the same plain, two-way, non-
 * mechanism split 8.1 already scoped in for this course (physical versus
 * human characteristic), applied here to one landmark at a time instead of
 * to a whole description. There is no third category, no ranking, and no
 * mechanism deciding which landmarks a community has; the row only asks
 * which of the two established kinds a given, already-named landmark is.
 * The three MCQ try_yourself items are written as recognition items, exactly
 * the way `m6geo-u1-mental-maps-and-spatial-thinking.ts` handles the same
 * format constraint for the same reason: the try_yourself format is
 * three-mcq and cannot itself ask a student to sketch anything, so the
 * sketching and describing this row's scope line asks for happens in the
 * two worked examples, where the tutor performs it aloud, and the
 * try_yourself items instead ask the student to check a printed, labeled
 * map against a printed description.
 *
 * CHECK-MOVE NOTE: geography's usual worked-example close (three independent
 * clues of different kinds, or rewind-then-contrast) does not fit a lesson
 * with no evidence to weigh and no numeric routine to invert. This file uses
 * an invented equivalent built for the skill this row owns: reread the
 * finished, labeled description landmark by landmark against the source,
 * confirming the order, the turn to the next landmark, and the label, all
 * three, at every stop (worked example 1's close). Worked example 2 extends
 * that same move one step further, since it is the one place this row
 * actually corrects a label: locate the single landmark whose label fails
 * the check, correct it by name, and then rerun the full landmark-by-
 * landmark check once more on the corrected map to confirm it now holds
 * together end to end. Reported as an invented equivalent, per the fan-out
 * contract's own allowance for a row where neither geography exemplar
 * variant fits.
 *
 * OPINION-vs-FORCED NOTE: a community map is personal, which makes an
 * opinion-answerable item a live risk here. Every try_yourself key in this
 * file is forced only by what the item's own printed description states,
 * never by a guess about what a real or typical community is probably like.
 * Item 1 (Willow Creek) and Item 3 (Sable Hollow) are forced because each
 * description states the order and the turns, and the correct label for
 * each landmark follows from what kind of thing it is -- built by people, or
 * occurring on its own -- a fact fixed independently of that community's
 * invented layout, never from an opinion about the layout itself. Item 2
 * (Bramblewood) is forced because the description's order and turns are
 * printed, and the friend's finished labels are printed too, so checking one
 * against the other is comparing print to print, not judging whose map is
 * better. No item anywhere asks the student to imagine or guess about a
 * community; every fact needed to answer sits inside the stem.
 *
 * ANSWER-CUE NOTE: written against deferred finding DF-3 (in the shipped
 * Grade 7 Geography bank the keyed answer was the strictly longest choice 67
 * percent of the time, 94 percent at difficulty 4; chance with four choices
 * is 25 percent). Every distractor here names a full, specific mismatch
 * (which landmark, which wrong label, or which stated fact from the
 * description it contradicts) rather than a short wrong label, and no key
 * was built to be the longest choice BECAUSE it is the key. Character counts
 * by choice (a, b, c, d), computed by script, not eyeballed, key marked
 * with *:
 *   Item 1 (try-which-labels-match-willow-creek): a=77 b=80* c=83 d=80 --
 *     key ranks 2nd of 4 by length, tied with d; c is longer than the key.
 *   Item 2 (try-whats-wrong-with-bramblewoods-map): a=83 b=89 c=165* d=119 --
 *     key ranks 1st (strictly longest) of 4 by length, because it is the
 *     only choice that states a full, specific, correct diagnosis (what
 *     matches, what does not, and why); the other three are honestly
 *     shorter because each states only one false claim.
 *   Item 3 (try-which-labels-match-sable-hollow): a=79 b=73 c=76 d=76* --
 *     key ranks 2nd of 4 by length, tied with c; a is longer than the key.
 * The key is the strictly longest choice in exactly one of the three items
 * (Item 2), which is reported as the honest diagnostic result, not a number
 * that was tuned -- see the contract's own note that three items cannot
 * distinguish chance from bias (0 or 1 is the ~84%-likely outcome under pure
 * chance). No key was shortened and no distractor was padded past what its
 * named mistake justifies to move this count. The three keys sit at ids b,
 * c, and d -- the id set `(8 + 4) mod 4 = 0` requires, omitting a.
 *
 * There are NO MAPS AND NO IMAGES in this course. Every item is solvable
 * from the words printed inside it.
 */

