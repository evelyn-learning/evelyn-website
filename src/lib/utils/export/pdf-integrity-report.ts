import { sanitize as baseSanitize } from './pdf-course-export';
import type { EnhancedAnalysisResult, ReportMetadata } from '@/components/plagiarism-detection/types';

export interface ComparisonPDFData {
  revisedResult: EnhancedAnalysisResult;
  changes: {
    summary: string;
    flaggedSectionsRemoved: number;
    flaggedSectionsRewritten: number;
    rewriteAppearsAIGenerated: boolean;
    addedText: string[];
    removedText: string[];
  };
}

/**
 * Extended sanitize that aggressively strips ALL characters outside the
 * WinAnsi range (U+0000–U+00FF) that jsPDF's built-in Helvetica can't render.
 * Without this, jsPDF switches to a fallback font with wrong glyph metrics,
 * causing the wide letter-spacing and overflow seen in the PDF.
 */
function sanitizeForPDF(text: string): string {
  let s = baseSanitize(text);

  // Common subscript/superscript (CO₂, x², etc.)
  s = s.replace(/\u2080/g, '0').replace(/\u2081/g, '1').replace(/\u2082/g, '2')
       .replace(/\u2083/g, '3').replace(/\u2084/g, '4').replace(/\u2085/g, '5')
       .replace(/\u2086/g, '6').replace(/\u2087/g, '7').replace(/\u2088/g, '8')
       .replace(/\u2089/g, '9');
  s = s.replace(/\u00B2/g, '2').replace(/\u00B3/g, '3').replace(/\u00B9/g, '1');

  // Ellipsis, special spaces, misc punctuation
  s = s.replace(/\u2026/g, '...');
  s = s.replace(/[\u00A0\u2000-\u200B\u202F\u205F\u3000]/g, ' ');
  s = s.replace(/\uFEFF/g, '');
  s = s.replace(/\u2027/g, '-');
  s = s.replace(/[\u2032\u2033]/g, "'");

  // Final catch-all: replace any remaining characters above U+00FF with '?'
  // This prevents jsPDF from ever hitting an unrenderable glyph.
  s = s.replace(/[^\x00-\xFF]/g, '?');

  return s;
}

export async function exportIntegrityReportPDF(
  submittedText: string,
  result: EnhancedAnalysisResult,
  metadata: ReportMetadata,
  comparisonData?: ComparisonPDFData
): Promise<void> {
  const { default: jsPDF } = await import('jspdf');
  const pdf = new jsPDF('p', 'mm', 'a4');
  const pageWidth = pdf.internal.pageSize.getWidth();
  const margin = 18;
  const contentWidth = pageWidth - margin * 2;
  const textAreaWidth = contentWidth - 8; // Inset for body text
  let y = 0;

  const LINE_HEIGHT = 4.5; // Consistent line height for body text

  const addPageIfNeeded = (space: number) => {
    if (y + space > 272) {
      pdf.addPage();
      y = 20;
    }
  };

  /**
   * Helper: reset font to a known-good state, render wrapped text.
   * This prevents font corruption from carrying across sections.
   */
  const drawWrappedText = (
    text: string,
    x: number,
    maxWidth: number,
    opts: { size?: number; style?: string; color?: [number, number, number]; lineHeight?: number } = {}
  ) => {
    const { size = 9, style = 'normal', color = [74, 85, 104], lineHeight = LINE_HEIGHT } = opts;
    pdf.setFont('helvetica', style);
    pdf.setFontSize(size);
    pdf.setTextColor(...color);
    const safe = sanitizeForPDF(text);
    const lines: string[] = pdf.splitTextToSize(safe, maxWidth);
    for (const line of lines) {
      addPageIfNeeded(lineHeight + 1);
      pdf.text(line, x, y);
      y += lineHeight;
    }
  };

  // ── Header Banner ──
  pdf.setFillColor(234, 88, 12);
  pdf.rect(0, 0, pageWidth, 38, 'F');
  pdf.setFillColor(220, 38, 38);
  pdf.rect(0, 35, pageWidth, 3, 'F');

  pdf.setTextColor(255, 255, 255);
  pdf.setFontSize(20);
  pdf.setFont('helvetica', 'bold');
  pdf.text('Academic Integrity Report', margin, 16);
  pdf.setFontSize(10);
  pdf.setFont('helvetica', 'normal');
  pdf.text('Generated by Evelyn Learning', margin, 24);
  pdf.text(sanitizeForPDF(metadata.analysisDate), margin, 30);

  y = 48;

  // ── Student / Assignment Info ──
  if (metadata.studentName) {
    drawWrappedText(`Student: ${metadata.studentName}`, margin, contentWidth, {
      size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 6,
    });
  }
  if (metadata.assignmentName) {
    drawWrappedText(`Assignment: ${metadata.assignmentName}`, margin, contentWidth, {
      size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 6,
    });
  }
  y += 4;

  // ── Overall Score ──
  const scoreColor: [number, number, number] = result.overallScore >= 60
    ? [22, 163, 74]
    : result.overallScore >= 30
    ? [202, 138, 4]
    : [220, 38, 38];

  addPageIfNeeded(28);
  pdf.setFillColor(248, 250, 252);
  pdf.roundedRect(margin, y, contentWidth, 22, 3, 3, 'F');

  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(13);
  pdf.setTextColor(26, 32, 44);
  pdf.text('Overall Originality Score', margin + 6, y + 9);

  pdf.setFontSize(22);
  pdf.setTextColor(...scoreColor);
  pdf.text(`${result.overallScore}%`, margin + 6, y + 19);

  pdf.setFontSize(10);
  pdf.setFont('helvetica', 'normal');
  pdf.setTextColor(100, 116, 139);
  pdf.text(sanitizeForPDF(result.overallVerdict), margin + 40, y + 19);
  y += 30;

  // ── Score Cards (AI + Plagiarism) ──
  addPageIfNeeded(34);
  const cardWidth = contentWidth / 2 - 3;

  // AI card
  pdf.setFillColor(243, 232, 255);
  pdf.roundedRect(margin, y, cardWidth, 28, 2, 2, 'F');
  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(10);
  pdf.setTextColor(88, 28, 135);
  pdf.text('AI Detection Score', margin + 4, y + 8);
  pdf.setFontSize(18);
  pdf.text(`${result.aiDetection.score}%`, margin + 4, y + 18);
  pdf.setFont('helvetica', 'normal');
  pdf.setFontSize(8);
  const aiVLines: string[] = pdf.splitTextToSize(sanitizeForPDF(result.aiDetection.verdict), cardWidth - 10);
  pdf.text(aiVLines, margin + 4, y + 24);

  // Plagiarism card
  const rightX = margin + contentWidth / 2 + 3;
  pdf.setFillColor(255, 237, 213);
  pdf.roundedRect(rightX, y, cardWidth, 28, 2, 2, 'F');
  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(10);
  pdf.setTextColor(154, 52, 18);
  pdf.text('Plagiarism Score', rightX + 4, y + 8);
  pdf.setFontSize(18);
  pdf.text(`${result.plagiarism.score}%`, rightX + 4, y + 18);
  pdf.setFont('helvetica', 'normal');
  pdf.setFontSize(8);
  const plVLines: string[] = pdf.splitTextToSize(sanitizeForPDF(result.plagiarism.verdict), cardWidth - 10);
  pdf.text(plVLines, rightX + 4, y + 24);
  y += 36;

  // ── Plagiarism Source Matches ──
  const sourceMatches = result.plagiarism.sourceMatches || [];
  if (sourceMatches.length > 0) {
    addPageIfNeeded(14);
    drawWrappedText('Plagiarism Source Matches', margin, contentWidth, {
      size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 7,
    });

    if (result.plagiarism.copyscapePercent) {
      drawWrappedText(
        `Web search found ${result.plagiarism.copyscapePercent}% of submitted text matching online sources.`,
        margin + 4, textAreaWidth,
        { size: 9, style: 'italic', color: [29, 78, 216] }
      );
      y += 2;
    }

    for (const match of sourceMatches) {
      addPageIfNeeded(20);

      // Verified badge or unverified indicator
      if (match.verified) {
        pdf.setFont('helvetica', 'bold');
        pdf.setFontSize(7);
        const badgeW = pdf.getTextWidth('WEB MATCH') + 6;
        pdf.setFillColor(59, 130, 246);
        pdf.roundedRect(margin, y - 3, badgeW, 4.5, 1, 1, 'F');
        pdf.setTextColor(255, 255, 255);
        pdf.text('WEB MATCH', margin + 3, y);
        y += 5;
      }

      // Title + percent
      drawWrappedText(
        `${match.title}  --  ${match.matchPercent}% match`,
        margin + 4, textAreaWidth,
        { size: 9, style: 'bold', color: match.verified ? [29, 78, 216] : [234, 88, 12] }
      );

      // URL
      if (match.url) {
        drawWrappedText(match.url, margin + 4, textAreaWidth, {
          size: 8, style: 'normal', color: [59, 130, 246],
        });
      }

      // Snippet
      if (match.verified && match.snippetText) {
        drawWrappedText(`"${match.snippetText}"`, margin + 8, textAreaWidth - 4, {
          size: 8, style: 'italic', color: [107, 114, 128],
        });
      }

      if (match.verified && match.wordsMatched) {
        drawWrappedText(`${match.wordsMatched} words matched`, margin + 4, textAreaWidth, {
          size: 7.5, style: 'normal', color: [156, 163, 175],
        });
      }

      y += 3;
    }
    y += 2;
  }

  // ── AI Detection Indicators ──
  if (result.aiDetection.indicators.length > 0) {
    addPageIfNeeded(14);
    drawWrappedText('AI Detection Indicators', margin, contentWidth, {
      size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 7,
    });

    if (result.aiDetection.modelAttribution) {
      drawWrappedText(result.aiDetection.modelAttribution, margin + 4, textAreaWidth, {
        size: 9, style: 'italic', color: [88, 28, 135],
      });
      y += 1;
    }

    for (const indicator of result.aiDetection.indicators) {
      drawWrappedText(`- ${indicator}`, margin + 4, textAreaWidth, {
        size: 9, style: 'normal', color: [74, 85, 104],
      });
      y += 1;
    }
    y += 3;
  }

  // ── Flagged Passages ──
  const annotations = result.annotations || [];
  if (annotations.length > 0) {
    addPageIfNeeded(14);
    drawWrappedText('Flagged Passages', margin, contentWidth, {
      size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 8,
    });

    const typeLabels: Record<string, string> = {
      'ai-generated': 'AI-GENERATED',
      suspicious: 'NEEDS REVIEW',
      plagiarism: 'PLAGIARISM',
    };
    const typeColors: Record<string, [number, number, number]> = {
      'ai-generated': [220, 38, 38],
      suspicious: [202, 138, 4],
      plagiarism: [234, 88, 12],
    };

    for (const ann of annotations) {
      addPageIfNeeded(22);

      // Type badge
      pdf.setFont('helvetica', 'bold');
      pdf.setFontSize(7);
      const badgeText = typeLabels[ann.type] || 'FLAGGED';
      const badgeW = pdf.getTextWidth(badgeText) + 6;
      const badgeColor = typeColors[ann.type] || [107, 114, 128];
      pdf.setFillColor(...badgeColor);
      pdf.roundedRect(margin, y - 3, badgeW, 4.5, 1, 1, 'F');
      pdf.setTextColor(255, 255, 255);
      pdf.text(badgeText, margin + 3, y);
      y += 5;

      // Quoted text — italic, dark gray
      const quotedText = `"${ann.matchedText}"`;
      drawWrappedText(quotedText, margin + 4, textAreaWidth, {
        size: 9, style: 'italic', color: [55, 65, 81],
      });
      y += 1;

      // Reason — normal, lighter
      drawWrappedText(ann.reason, margin + 4, textAreaWidth, {
        size: 8.5, style: 'normal', color: [100, 116, 139],
      });
      y += 4;
    }
  }

  // ── Concerns ──
  if (result.concerns.length > 0) {
    addPageIfNeeded(14);
    drawWrappedText('Concerns', margin, contentWidth, {
      size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 8,
    });

    for (const concern of result.concerns) {
      addPageIfNeeded(14);

      // Severity + type on one line
      const sevColor: [number, number, number] =
        concern.severity === 'high' ? [220, 38, 38]
        : concern.severity === 'medium' ? [202, 138, 4]
        : [59, 130, 246];

      drawWrappedText(
        `${concern.severity.toUpperCase()}  --  ${concern.type}`,
        margin + 4, textAreaWidth,
        { size: 8.5, style: 'bold', color: sevColor, lineHeight: 5 }
      );

      // Description
      drawWrappedText(concern.description, margin + 4, textAreaWidth, {
        size: 9, style: 'normal', color: [74, 85, 104],
      });

      // Suggestion
      if (concern.suggestion) {
        drawWrappedText(`Suggestion: ${concern.suggestion}`, margin + 4, textAreaWidth, {
          size: 8.5, style: 'italic', color: [100, 116, 139],
        });
      }
      y += 3;
    }
  }

  // ── Recommendations ──
  if (result.recommendations.length > 0) {
    addPageIfNeeded(14);
    drawWrappedText('Recommendations', margin, contentWidth, {
      size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 8,
    });

    for (const rec of result.recommendations) {
      drawWrappedText(`- ${rec}`, margin + 4, textAreaWidth, {
        size: 9, style: 'normal', color: [74, 85, 104],
      });
      y += 1;
    }
  }

  // ── Comparison Section ──
  if (comparisonData) {
    addPageIfNeeded(20);
    y += 6;

    // Section divider
    pdf.setDrawColor(59, 130, 246);
    pdf.setLineWidth(0.8);
    pdf.line(margin, y, pageWidth - margin, y);
    y += 8;

    drawWrappedText('Resubmission Comparison', margin, contentWidth, {
      size: 14, style: 'bold', color: [26, 32, 44], lineHeight: 8,
    });
    y += 2;

    // Change Summary box
    addPageIfNeeded(30);
    const summaryBg: [number, number, number] = comparisonData.changes.rewriteAppearsAIGenerated
      ? [254, 242, 242] : [240, 253, 244];
    pdf.setFillColor(...summaryBg);
    pdf.roundedRect(margin, y, contentWidth, 8, 2, 2, 'F');
    drawWrappedText('Change Summary', margin + 4, textAreaWidth, {
      size: 10, style: 'bold', color: [26, 32, 44], lineHeight: 6,
    });
    drawWrappedText(comparisonData.changes.summary, margin + 4, textAreaWidth, {
      size: 9, style: 'normal', color: [55, 65, 81],
    });
    y += 3;

    // Change stats
    addPageIfNeeded(16);
    const stats = [
      `Flagged Sections Removed: ${comparisonData.changes.flaggedSectionsRemoved}`,
      `Sections Rewritten: ${comparisonData.changes.flaggedSectionsRewritten}`,
      `New Passages Added: ${comparisonData.changes.addedText.length}`,
      `Rewrite Appears AI-Generated: ${comparisonData.changes.rewriteAppearsAIGenerated ? 'Yes' : 'No'}`,
    ];
    for (const stat of stats) {
      const isAIGenWarning = stat.includes('AI-Generated: Yes');
      drawWrappedText(stat, margin + 4, textAreaWidth, {
        size: 9, style: 'bold',
        color: isAIGenWarning ? [220, 38, 38] : [74, 85, 104],
        lineHeight: 5.5,
      });
    }
    y += 4;

    // Revised Submission Scores
    addPageIfNeeded(34);
    drawWrappedText('Revised Submission Analysis', margin, contentWidth, {
      size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 8,
    });

    const rv = comparisonData.revisedResult;
    const rvScoreColor: [number, number, number] = rv.overallScore >= 60
      ? [22, 163, 74] : rv.overallScore >= 30 ? [202, 138, 4] : [220, 38, 38];

    // Revised overall score box
    addPageIfNeeded(28);
    pdf.setFillColor(248, 250, 252);
    pdf.roundedRect(margin, y, contentWidth, 22, 3, 3, 'F');
    pdf.setFont('helvetica', 'bold');
    pdf.setFontSize(13);
    pdf.setTextColor(26, 32, 44);
    pdf.text('Revised Overall Originality Score', margin + 6, y + 9);
    pdf.setFontSize(22);
    pdf.setTextColor(...rvScoreColor);
    pdf.text(`${rv.overallScore}%`, margin + 6, y + 19);
    pdf.setFontSize(10);
    pdf.setFont('helvetica', 'normal');
    pdf.setTextColor(100, 116, 139);
    pdf.text(sanitizeForPDF(rv.overallVerdict), margin + 40, y + 19);
    y += 30;

    // Revised score cards
    addPageIfNeeded(34);
    // AI card
    pdf.setFillColor(243, 232, 255);
    pdf.roundedRect(margin, y, cardWidth, 28, 2, 2, 'F');
    pdf.setFont('helvetica', 'bold');
    pdf.setFontSize(10);
    pdf.setTextColor(88, 28, 135);
    pdf.text('AI Detection Score', margin + 4, y + 8);
    pdf.setFontSize(18);
    pdf.text(`${rv.aiDetection.score}%`, margin + 4, y + 18);
    pdf.setFont('helvetica', 'normal');
    pdf.setFontSize(8);
    const rvAiVLines: string[] = pdf.splitTextToSize(sanitizeForPDF(rv.aiDetection.verdict), cardWidth - 10);
    pdf.text(rvAiVLines, margin + 4, y + 24);

    // Plagiarism card
    pdf.setFillColor(255, 237, 213);
    pdf.roundedRect(rightX, y, cardWidth, 28, 2, 2, 'F');
    pdf.setFont('helvetica', 'bold');
    pdf.setFontSize(10);
    pdf.setTextColor(154, 52, 18);
    pdf.text('Plagiarism Score', rightX + 4, y + 8);
    pdf.setFontSize(18);
    pdf.text(`${rv.plagiarism.score}%`, rightX + 4, y + 18);
    pdf.setFont('helvetica', 'normal');
    pdf.setFontSize(8);
    const rvPlVLines: string[] = pdf.splitTextToSize(sanitizeForPDF(rv.plagiarism.verdict), cardWidth - 10);
    pdf.text(rvPlVLines, rightX + 4, y + 24);
    y += 36;

    // Revised flagged passages
    const rvAnnotations = rv.annotations || [];
    if (rvAnnotations.length > 0) {
      addPageIfNeeded(14);
      drawWrappedText('Revised Submission -- Flagged Passages', margin, contentWidth, {
        size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 8,
      });

      const typeLabels: Record<string, string> = {
        'ai-generated': 'AI-GENERATED',
        suspicious: 'NEEDS REVIEW',
        plagiarism: 'PLAGIARISM',
      };
      const typeColors: Record<string, [number, number, number]> = {
        'ai-generated': [220, 38, 38],
        suspicious: [202, 138, 4],
        plagiarism: [234, 88, 12],
      };

      for (const ann of rvAnnotations) {
        addPageIfNeeded(22);
        pdf.setFont('helvetica', 'bold');
        pdf.setFontSize(7);
        const badgeText = typeLabels[ann.type] || 'FLAGGED';
        const badgeW = pdf.getTextWidth(badgeText) + 6;
        const badgeColor = typeColors[ann.type] || [107, 114, 128];
        pdf.setFillColor(...badgeColor);
        pdf.roundedRect(margin, y - 3, badgeW, 4.5, 1, 1, 'F');
        pdf.setTextColor(255, 255, 255);
        pdf.text(badgeText, margin + 3, y);
        y += 5;
        drawWrappedText(`"${ann.matchedText}"`, margin + 4, textAreaWidth, {
          size: 9, style: 'italic', color: [55, 65, 81],
        });
        y += 1;
        drawWrappedText(ann.reason, margin + 4, textAreaWidth, {
          size: 8.5, style: 'normal', color: [100, 116, 139],
        });
        y += 4;
      }
    } else {
      drawWrappedText('No flagged passages in revised submission.', margin + 4, textAreaWidth, {
        size: 9, style: 'italic', color: [22, 163, 74],
      });
      y += 2;
    }

    // Removed passages
    if (comparisonData.changes.removedText.length > 0) {
      addPageIfNeeded(14);
      drawWrappedText('Removed Passages', margin, contentWidth, {
        size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 8,
      });
      for (const text of comparisonData.changes.removedText) {
        addPageIfNeeded(12);
        drawWrappedText(`"${text}"`, margin + 4, textAreaWidth, {
          size: 9, style: 'italic', color: [153, 27, 27],
        });
        y += 3;
      }
    }

    // Added passages
    if (comparisonData.changes.addedText.length > 0) {
      addPageIfNeeded(14);
      drawWrappedText('Added Passages', margin, contentWidth, {
        size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 8,
      });
      for (const text of comparisonData.changes.addedText) {
        addPageIfNeeded(12);
        drawWrappedText(`"${text}"`, margin + 4, textAreaWidth, {
          size: 9, style: 'italic', color: [22, 101, 52],
        });
        y += 3;
      }
    }
  }

  // ── Teacher Notes ──
  if (metadata.teacherNotes) {
    addPageIfNeeded(18);
    y += 4;
    drawWrappedText('Teacher Notes', margin, contentWidth, {
      size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 8,
    });
    drawWrappedText(metadata.teacherNotes, margin + 4, textAreaWidth, {
      size: 9, style: 'normal', color: [55, 65, 81],
    });
  }

  // ── Footer on every page ──
  const totalPages = pdf.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    pdf.setPage(i);
    pdf.setDrawColor(226, 232, 240);
    pdf.line(margin, 282, pageWidth - margin, 282);
    pdf.setFont('helvetica', 'normal');
    pdf.setFontSize(7);
    pdf.setTextColor(156, 163, 175);
    pdf.text('Generated by Evelyn Learning -- FERPA compliant analysis tool', margin, 287);
    pdf.text(`Page ${i} of ${totalPages}`, pageWidth - margin - 22, 287);
  }

  const filename = [
    metadata.studentName || 'Student',
    metadata.assignmentName || 'Report',
    'Integrity_Report',
  ]
    .join('_')
    .replace(/[^a-zA-Z0-9_]+/g, '_')
    + '.pdf';

  pdf.save(filename);
}

/**
 * Same as exportIntegrityReportPDF but returns a Blob instead of triggering
 * a download. Used by batch export to collect multiple PDFs into a ZIP.
 */
export async function generateIntegrityReportBlob(
  submittedText: string,
  result: EnhancedAnalysisResult,
  metadata: ReportMetadata
): Promise<Blob> {
  // We re-use the same generation logic but capture the output as a blob.
  // To avoid duplicating 200+ lines, we build the PDF via an internal helper.
  const { default: jsPDF } = await import('jspdf');
  const pdf = new jsPDF('p', 'mm', 'a4');
  const pageWidth = pdf.internal.pageSize.getWidth();
  const margin = 18;
  const contentWidth = pageWidth - margin * 2;
  const textAreaWidth = contentWidth - 8;
  let y = 0;
  const LINE_HEIGHT = 4.5;

  const addPageIfNeeded = (space: number) => {
    if (y + space > 272) { pdf.addPage(); y = 20; }
  };

  const drawWrappedText = (
    text: string, x: number, maxWidth: number,
    opts: { size?: number; style?: string; color?: [number, number, number]; lineHeight?: number } = {}
  ) => {
    const { size = 9, style = 'normal', color = [74, 85, 104], lineHeight = LINE_HEIGHT } = opts;
    pdf.setFont('helvetica', style);
    pdf.setFontSize(size);
    pdf.setTextColor(...color);
    const safe = sanitizeForPDF(text);
    const lines: string[] = pdf.splitTextToSize(safe, maxWidth);
    for (const line of lines) {
      addPageIfNeeded(lineHeight + 1);
      pdf.text(line, x, y);
      y += lineHeight;
    }
  };

  // Header
  pdf.setFillColor(234, 88, 12);
  pdf.rect(0, 0, pageWidth, 38, 'F');
  pdf.setFillColor(220, 38, 38);
  pdf.rect(0, 35, pageWidth, 3, 'F');
  pdf.setTextColor(255, 255, 255);
  pdf.setFontSize(20);
  pdf.setFont('helvetica', 'bold');
  pdf.text('Academic Integrity Report', margin, 16);
  pdf.setFontSize(10);
  pdf.setFont('helvetica', 'normal');
  pdf.text('Generated by Evelyn Learning', margin, 24);
  pdf.text(sanitizeForPDF(metadata.analysisDate), margin, 30);
  y = 48;

  if (metadata.studentName) {
    drawWrappedText(`Student: ${metadata.studentName}`, margin, contentWidth, { size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 6 });
  }
  if (metadata.assignmentName) {
    drawWrappedText(`Assignment: ${metadata.assignmentName}`, margin, contentWidth, { size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 6 });
  }
  y += 4;

  // Scores
  drawWrappedText(`Overall Originality: ${result.overallScore}% -- ${result.overallVerdict}`, margin, contentWidth, { size: 10, style: 'bold', color: [26, 32, 44], lineHeight: 6 });
  drawWrappedText(`AI Detection: ${result.aiDetection.score}% -- ${result.aiDetection.verdict}`, margin, contentWidth, { size: 10, style: 'normal', color: [88, 28, 135], lineHeight: 6 });
  drawWrappedText(`Plagiarism: ${result.plagiarism.score}% -- ${result.plagiarism.verdict}`, margin, contentWidth, { size: 10, style: 'normal', color: [154, 52, 18], lineHeight: 6 });
  y += 4;

  // Source Matches
  const blobSourceMatches = result.plagiarism.sourceMatches || [];
  if (blobSourceMatches.length > 0) {
    drawWrappedText('Plagiarism Source Matches', margin, contentWidth, { size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 8 });
    if (result.plagiarism.copyscapePercent) {
      drawWrappedText(`Web search: ${result.plagiarism.copyscapePercent}% matched online.`, margin + 4, textAreaWidth, { size: 9, style: 'italic', color: [29, 78, 216] });
      y += 1;
    }
    for (const match of blobSourceMatches) {
      addPageIfNeeded(14);
      const label = match.verified ? '[WEB MATCH]' : '[PATTERN MATCH]';
      const labelColor: [number, number, number] = match.verified ? [29, 78, 216] : [234, 88, 12];
      drawWrappedText(`${label} ${match.title} -- ${match.matchPercent}%`, margin + 4, textAreaWidth, { size: 9, style: 'bold', color: labelColor, lineHeight: 5 });
      if (match.url) {
        drawWrappedText(match.url, margin + 4, textAreaWidth, { size: 8, color: [59, 130, 246] });
      }
      if (match.verified && match.snippetText) {
        drawWrappedText(`"${match.snippetText}"`, margin + 8, textAreaWidth - 4, { size: 8, style: 'italic', color: [107, 114, 128] });
      }
      y += 2;
    }
    y += 2;
  }

  // Annotations
  if (result.annotations.length > 0) {
    drawWrappedText('Flagged Passages', margin, contentWidth, { size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 8 });
    for (const ann of result.annotations) {
      addPageIfNeeded(16);
      drawWrappedText(`[${ann.type.toUpperCase()}]`, margin + 4, textAreaWidth, { size: 8, style: 'bold', color: [107, 114, 128], lineHeight: 5 });
      drawWrappedText(`"${ann.matchedText}"`, margin + 4, textAreaWidth, { size: 9, style: 'italic', color: [55, 65, 81] });
      drawWrappedText(ann.reason, margin + 4, textAreaWidth, { size: 8.5, style: 'normal', color: [100, 116, 139] });
      y += 3;
    }
  }

  // Concerns
  if (result.concerns.length > 0) {
    drawWrappedText('Concerns', margin, contentWidth, { size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 8 });
    for (const concern of result.concerns) {
      addPageIfNeeded(12);
      const sevColor: [number, number, number] = concern.severity === 'high' ? [220, 38, 38] : concern.severity === 'medium' ? [202, 138, 4] : [59, 130, 246];
      drawWrappedText(`${concern.severity.toUpperCase()} -- ${concern.type}`, margin + 4, textAreaWidth, { size: 8.5, style: 'bold', color: sevColor, lineHeight: 5 });
      drawWrappedText(concern.description, margin + 4, textAreaWidth, { size: 9, color: [74, 85, 104] });
      y += 2;
    }
  }

  // Recommendations
  if (result.recommendations.length > 0) {
    drawWrappedText('Recommendations', margin, contentWidth, { size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 8 });
    for (const rec of result.recommendations) {
      drawWrappedText(`- ${rec}`, margin + 4, textAreaWidth, { size: 9, color: [74, 85, 104] });
      y += 1;
    }
  }

  // Footer
  const totalPages = pdf.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    pdf.setPage(i);
    pdf.setDrawColor(226, 232, 240);
    pdf.line(margin, 282, pageWidth - margin, 282);
    pdf.setFont('helvetica', 'normal');
    pdf.setFontSize(7);
    pdf.setTextColor(156, 163, 175);
    pdf.text('Generated by Evelyn Learning -- FERPA compliant analysis tool', margin, 287);
    pdf.text(`Page ${i} of ${totalPages}`, pageWidth - margin - 22, 287);
  }

  return pdf.output('blob');
}
