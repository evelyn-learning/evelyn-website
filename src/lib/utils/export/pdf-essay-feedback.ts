import { sanitize as baseSanitize } from './pdf-course-export';

interface Category {
  name: string;
  score: number;
  observations: string[];
  suggestions: string[];
}

interface RewriteExample {
  original: string;
  improved: string;
  explanation: string;
}

export interface EssayFeedbackPDFData {
  categories: Category[];
  overallScore: number;
  overallAssessment: string;
  priorityImprovements: string[];
  rewriteExample: RewriteExample;
}

function sanitizeForPDF(text: string): string {
  let s = baseSanitize(text);
  s = s.replace(/\u2080/g, '0').replace(/\u2081/g, '1').replace(/\u2082/g, '2')
       .replace(/\u2083/g, '3').replace(/\u2084/g, '4').replace(/\u2085/g, '5')
       .replace(/\u2086/g, '6').replace(/\u2087/g, '7').replace(/\u2088/g, '8')
       .replace(/\u2089/g, '9');
  s = s.replace(/\u00B2/g, '2').replace(/\u00B3/g, '3').replace(/\u00B9/g, '1');
  s = s.replace(/\u2026/g, '...');
  s = s.replace(/[\u00A0\u2000-\u200B\u202F\u205F\u3000]/g, ' ');
  s = s.replace(/\uFEFF/g, '');
  s = s.replace(/\u2027/g, '-');
  s = s.replace(/[\u2032\u2033]/g, "'");
  s = s.replace(/[^\x00-\xFF]/g, '?');
  return s;
}

export async function exportEssayFeedbackPDF(
  essayText: string,
  feedback: EssayFeedbackPDFData,
  rubricName: string,
  maxScore: number
): Promise<void> {
  const { default: jsPDF } = await import('jspdf');
  const pdf = new jsPDF('p', 'mm', 'a4');
  const pageWidth = pdf.internal.pageSize.getWidth();
  const margin = 18;
  const contentWidth = pageWidth - margin * 2;
  const textAreaWidth = contentWidth - 8;
  let y = 0;
  const LINE_HEIGHT = 4.5;

  const addPageIfNeeded = (space: number) => {
    if (y + space > 272) { pdf.addPage(); y = 20; }
  };

  const drawWrappedText = (
    text: string, x: number, maxWidth: number,
    opts: { size?: number; style?: string; color?: [number, number, number]; lineHeight?: number } = {}
  ) => {
    const { size = 9, style = 'normal', color = [74, 85, 104], lineHeight = LINE_HEIGHT } = opts;
    pdf.setFont('helvetica', style);
    pdf.setFontSize(size);
    pdf.setTextColor(...color);
    const safe = sanitizeForPDF(text);
    const lines: string[] = pdf.splitTextToSize(safe, maxWidth);
    for (const line of lines) {
      addPageIfNeeded(lineHeight + 1);
      pdf.text(line, x, y);
      y += lineHeight;
    }
  };

  // ── Header Banner ──
  pdf.setFillColor(147, 51, 234); // purple-600
  pdf.rect(0, 0, pageWidth, 38, 'F');
  pdf.setFillColor(126, 34, 206); // purple-700
  pdf.rect(0, 35, pageWidth, 3, 'F');

  pdf.setTextColor(255, 255, 255);
  pdf.setFontSize(20);
  pdf.setFont('helvetica', 'bold');
  pdf.text('Essay Feedback Report', margin, 16);
  pdf.setFontSize(10);
  pdf.setFont('helvetica', 'normal');
  pdf.text('Generated by Evelyn Learning', margin, 24);
  const dateStr = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
  pdf.text(sanitizeForPDF(dateStr), margin, 30);
  y = 48;

  // ── Rubric & Word Count ──
  const wordCount = essayText.trim().split(/\s+/).filter(w => w).length;
  drawWrappedText(`Rubric: ${rubricName}`, margin, contentWidth, {
    size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 6,
  });
  drawWrappedText(`Word Count: ${wordCount}`, margin, contentWidth, {
    size: 10, style: 'normal', color: [100, 116, 139], lineHeight: 6,
  });
  y += 4;

  // ── Overall Score ──
  const percentage = Math.round((feedback.overallScore / maxScore) * 100);
  const scoreColor: [number, number, number] = percentage >= 80
    ? [22, 163, 74] : percentage >= 60 ? [147, 51, 234] : percentage >= 40 ? [202, 138, 4] : [220, 38, 38];

  addPageIfNeeded(28);
  pdf.setFillColor(248, 250, 252);
  pdf.roundedRect(margin, y, contentWidth, 22, 3, 3, 'F');
  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(13);
  pdf.setTextColor(26, 32, 44);
  pdf.text('Overall Score', margin + 6, y + 9);
  pdf.setFontSize(22);
  pdf.setTextColor(...scoreColor);
  pdf.text(`${feedback.overallScore.toFixed(1)}/${maxScore}`, margin + 6, y + 19);
  pdf.setFontSize(10);
  pdf.setFont('helvetica', 'normal');
  pdf.setTextColor(100, 116, 139);
  pdf.text(`(${percentage}%)`, margin + 50, y + 19);
  y += 30;

  // Overall assessment
  drawWrappedText(feedback.overallAssessment, margin + 4, textAreaWidth, {
    size: 9, style: 'italic', color: [55, 65, 81],
  });
  y += 4;

  // ── Category Scores ──
  addPageIfNeeded(14);
  drawWrappedText('Category Breakdown', margin, contentWidth, {
    size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 8,
  });

  for (const cat of feedback.categories) {
    addPageIfNeeded(20);
    const catPct = Math.round((cat.score / maxScore) * 100);
    const barColor: [number, number, number] = catPct >= 80
      ? [16, 185, 129] : catPct >= 60 ? [147, 51, 234] : catPct >= 40 ? [234, 179, 8] : [239, 68, 68];

    // Category name and score
    pdf.setFont('helvetica', 'bold');
    pdf.setFontSize(10);
    pdf.setTextColor(26, 32, 44);
    pdf.text(sanitizeForPDF(cat.name), margin + 4, y);
    pdf.text(`${cat.score}/${maxScore}`, margin + contentWidth - 20, y);
    y += 4;

    // Score bar
    pdf.setFillColor(229, 231, 235);
    pdf.roundedRect(margin + 4, y, textAreaWidth, 3, 1.5, 1.5, 'F');
    pdf.setFillColor(...barColor);
    pdf.roundedRect(margin + 4, y, textAreaWidth * (catPct / 100), 3, 1.5, 1.5, 'F');
    y += 7;

    // Strengths
    if (cat.observations.length > 0) {
      for (const obs of cat.observations) {
        drawWrappedText(`+ ${obs}`, margin + 8, textAreaWidth - 4, {
          size: 8.5, style: 'normal', color: [22, 163, 74],
        });
        y += 0.5;
      }
    }

    // Suggestions
    if (cat.suggestions.length > 0) {
      for (const sug of cat.suggestions) {
        drawWrappedText(`> ${sug}`, margin + 8, textAreaWidth - 4, {
          size: 8.5, style: 'normal', color: [147, 51, 234],
        });
        y += 0.5;
      }
    }
    y += 4;
  }

  // ── Priority Improvements ──
  if (feedback.priorityImprovements.length > 0) {
    addPageIfNeeded(14);
    drawWrappedText('Priority Improvements', margin, contentWidth, {
      size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 8,
    });

    feedback.priorityImprovements.forEach((imp, idx) => {
      addPageIfNeeded(10);
      drawWrappedText(`${idx + 1}. ${imp}`, margin + 4, textAreaWidth, {
        size: 9, style: 'normal', color: [180, 83, 9],
      });
      y += 2;
    });
  }

  // ── Rewrite Example ──
  if (feedback.rewriteExample) {
    addPageIfNeeded(30);
    y += 2;
    drawWrappedText('Sentence Improvement Example', margin, contentWidth, {
      size: 11, style: 'bold', color: [26, 32, 44], lineHeight: 8,
    });

    // Original
    addPageIfNeeded(16);
    pdf.setFillColor(254, 242, 242);
    pdf.roundedRect(margin, y - 2, contentWidth, 4, 2, 2, 'F');
    drawWrappedText('ORIGINAL', margin + 4, textAreaWidth, {
      size: 7, style: 'bold', color: [220, 38, 38], lineHeight: 4,
    });
    drawWrappedText(`"${feedback.rewriteExample.original}"`, margin + 4, textAreaWidth, {
      size: 9, style: 'italic', color: [153, 27, 27],
    });
    y += 4;

    // Improved
    addPageIfNeeded(16);
    pdf.setFillColor(240, 253, 244);
    pdf.roundedRect(margin, y - 2, contentWidth, 4, 2, 2, 'F');
    drawWrappedText('IMPROVED', margin + 4, textAreaWidth, {
      size: 7, style: 'bold', color: [22, 163, 74], lineHeight: 4,
    });
    drawWrappedText(`"${feedback.rewriteExample.improved}"`, margin + 4, textAreaWidth, {
      size: 9, style: 'italic', color: [22, 101, 52],
    });
    y += 4;

    // Explanation
    drawWrappedText(`Why this works: ${feedback.rewriteExample.explanation}`, margin + 4, textAreaWidth, {
      size: 8.5, style: 'normal', color: [74, 85, 104],
    });
  }

  // ── Footer on every page ──
  const totalPages = pdf.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    pdf.setPage(i);
    pdf.setDrawColor(226, 232, 240);
    pdf.line(margin, 282, pageWidth - margin, 282);
    pdf.setFont('helvetica', 'normal');
    pdf.setFontSize(7);
    pdf.setTextColor(156, 163, 175);
    pdf.text('Generated by Evelyn Learning -- AI Essay Feedback Tool', margin, 287);
    pdf.text(`Page ${i} of ${totalPages}`, pageWidth - margin - 22, 287);
  }

  const filename = `Essay_Feedback_${rubricName.replace(/[^a-zA-Z0-9]+/g, '_')}_${new Date().toISOString().split('T')[0]}.pdf`;
  pdf.save(filename);
}
